TEST(BubbleShapeTest, MatchesFishUi)
{
    for (const Reference& reference : kReferences) {
        BubbleShape shape;
        shape.width = reference.width;
        shape.height = reference.height;
        shape.radius = reference.radius;
        shape.continuousCorners = reference.continuous;
        shape.arrowEdge = reference.edge;
        shape.arrowPosition = reference.position;
        const std::string name = std::to_string(int(reference.edge)) + " " + std::to_string(reference.width);
        EXPECT_NEAR(shape.minimumEdgeLength(), reference.minimumEdgeLength, 1e-3) << name;
        EXPECT_EQ(shape.arrowVisible(), reference.arrowVisible) << name;
        EXPECT_EQ(shape.bodyRect(), reference.body) << name;
        const Path path = shape.path();
        const RectF bounds = path.boundingRect();
        EXPECT_NEAR(bounds.x, reference.bounds.x, 2e-3) << name;
        EXPECT_NEAR(bounds.y, reference.bounds.y, 2e-3) << name;
        EXPECT_NEAR(bounds.width, reference.bounds.width, 2e-3) << name;
        EXPECT_NEAR(bounds.height, reference.bounds.height, 2e-3) << name;

        std::string coverage;
        for (double y = 0.25; y < reference.height; y += 1.5) {
            for (double x = 0.25; x < reference.width; x += 1.5)
                coverage += path.contains({x, y}) ? '1' : '0';
        }
        ASSERT_EQ(coverage.size(), std::string(reference.coverage).size()) << name;
        int differences = 0;
        const size_t columns = size_t(std::ceil((reference.width - 0.25) / 1.5));
        for (size_t i = 0; i < coverage.size(); ++i) {
            if (coverage[i] == reference.coverage[i])
                continue;
            // Points exactly on the outline (the arrow's 45 degree sides cross
            // the grid's points) go either way.
            const PointF point = {0.25 + 1.5 * double(i % columns), 0.25 + 1.5 * double(i / columns)};
            bool onEdge = false;
            for (const PointF offset : {PointF{0.01, 0}, PointF{-0.01, 0}, PointF{0, 0.01}, PointF{0, -0.01}})
                onEdge = onEdge || path.contains({point.x + offset.x, point.y + offset.y}) != (coverage[i] == '1');
            if (onEdge)
                continue;
            ++differences;
            ADD_FAILURE() << name << " at " << point.x << ", " << point.y;
        }
        EXPECT_EQ(differences, 0) << name;
    }
}

TEST(BubbleShapeTest, ArcsAsTheCommonPathClass)
{
    Path path;
    path.moveTo(0, 0);
    path.arcTo({0, 0, 20, 20}, 90, -90);
    const RectF bounds = path.boundingRect();
    EXPECT_NEAR(bounds.right(), 20, 1e-9);
    EXPECT_NEAR(bounds.y, 0, 1e-9);
    // A line to the start, then a quarter turn clockwise on screen.
    const std::vector<Path::Element> elements = path.elements();
    ASSERT_EQ(elements.size(), 5u);
    EXPECT_EQ(elements[1].type, Path::Element::Type::LineTo);
    EXPECT_NEAR(elements[1].x, 10, 1e-9);
    EXPECT_NEAR(elements[4].x, 20, 1e-9);
    EXPECT_NEAR(elements[4].y, 10, 1e-9);
    // Nothing for an empty rect.
    path.arcTo({0, 0, 0, 0}, 0, 90);
    EXPECT_EQ(path.elements().size(), 5u);
}
